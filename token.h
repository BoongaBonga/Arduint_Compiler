#ifndef ARDUINT_TOKEN_H
#define ARDUINT_TOKEN_H

typedef enum {
  TOKEN_IDENTIFIER,
  TOKEN_NUMBER,
  TOKEN_STRING,

  // Control flow
  TOKEN_IF,
  TOKEN_ELSE,
  TOKEN_WHILE,
  TOKEN_FOR,
  TOKEN_LOOP,
  TOKEN_RETURN,
  TOKEN_FUNCTION,
  TOKEN_FALSE,
  TOKEN_TRUE,

  // Arduino operations
  TOKEN_SETPIN,
  TOKEN_ANALOG,
  TOKEN_READPIN,
  TOKEN_DELAY,
  TOKEN_DELAY_MICROS,
  TOKEN_PRINT,
  TOKEN_µS,
  TOKEN_MS,
  TOKEN_S,
  TOKEN_M,
  TOKEN_H,

  // Functions & keywords
  TOKEN_DEFINE,
  TOKEN_AS,
  TOKEN_TO,

  // Operators
  TOKEN_PLUS,
  TOKEN_MINUS,
  TOKEN_SLASH,
  TOKEN_STAR,
  TOKEN_POWER,
  TOKEN_AND,
  TOKEN_NOT,
  TOKEN_OR,

  // One-character tokens
  TOKEN_BACKSLASH,
  TOKEN_COMMA,
  TOKEN_POINT_COMMA,
  TOKEN_COLON,
  TOKEN_DOT,
  TOKEN_EQUALS,
  TOKEN_PERCENT,
  TOKEN_LEFT_SQUARE_BRACKET,
  TOKEN_RIGHT_SQUARE_BRACKET,
  TOKEN_LEFT_ROUND_BRACKET,
  TOKEN_RIGHT_ROUND_BRACKET,
  TOKEN_LEFT_SQUIGGLY_BRACKET,
  TOKEN_RIGHT_SQUIGGLY_BRACKET,
  TOKEN_LESS,
  TOKEN_GREATER,

  // Two-character tokens
  TOKEN_EQUALS_EQUALS,
  TOKEN_GREATER_EQUALS,
  TOKEN_LESS_EQUALS,
  TOKEN_NOT_EQUALS,

  TOKEN_MINUS_EQUALS,
  TOKEN_PLUS_EQUALS,
  TOKEN_SLASH_EQUALS,
  TOKEN_STAR_EQUALS,
  TOKEN_POWER_EQUALS,
  TOKEN_AND_EQUALS,
  TOKEN_OR_EQUALS,
  TOKEN_PERCENT_EQUALS,

  TOKEN_PLUS_PLUS,
  TOKEN_MINUS_MINUS,
  TOKEN_AND_AND,
  TOKEN_OR_OR,

  TOKEN_NEWLINE,
  TOKEN_ERROR,
  TOKEN_EOF,
} TokenType;

typedef struct {
  TokenType type;
  const char *start;
  int length;
  int line;
  int offset;
} Token;

#endif